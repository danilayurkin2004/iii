// Stages overlap: a student can also work, train, create and run a business.
function activeLifeStages(s){return {
 childhood:s.age<9&&!s.school?.started,
 school:schoolEnrolled(s),
 college:!!s.college,
 university:s.uni>0,
 side:!!s.side,
 work:!!s.job,
 sport:!!s.sport?.active&&!s.sport.records[s.sport.active]?.retired,
 creative:s.creativeHours>0,
 business:!!s.business,
 adult:s.age>=18&&s.alive,
};}
const schoolEventIds=new Set(['bully','sciencefair','examfear','hackathon','peerparty','mentor','scholarshipcontest','careerday','summerstudy','counselor','newstudent']);
function eventStage(e){if(e.phase)return e.phase;if(schoolEventIds.has(e.id)||['Трудная контрольная','Новая компания','Выбор кружка','Выбор школьного кружка'].includes(e.title))return 'school';if(e.title==='Непростая задача на работе')return 'work';if(e.title==='Сложный клиент')return 'side';if(['firstword','sleep','sharing'].includes(e.id)||['Первые открытия','Семейный вечер'].includes(e.title))return 'childhood';if(['campus','resit','internshipfair'].includes(e.id))return 'student';return {worker:'work',side:'side',earner:'earner',sport:'sport',creative:'creative'}[e.tag]||null;}
function eventEligible(s,e){if(!e||!s.alive)return false;const stages=activeLifeStages(s),phase=eventStage(e);if(phase==='student')return stages.college||stages.university;if(phase==='earner')return stages.work||stages.side;if(phase&& !stages[phase])return false;
 // Queued decisions from older saves also need their original context.
 if(e.choices?.some(c=>c.effect==='business')&&!stages.business)return false;
 if(e.choices?.some(c=>c.effect==='assignment')&&!stages.work)return false;
 if(e.title==='Другие планы'&&!stages.school&&!stages.college&&!stages.university)return false;
 return true;}
function pruneEventQueue(s){const valid=[s.event,...(s.pendingEvents||[])].filter(e=>eventEligible(s,e));s.event=valid.shift()||null;s.pendingEvents=valid;}

